describe('isPublicAddress',()=>{
 it('accepts well-known public IPv4 addresses',()=>{
  expect(isPublicAddress('1.1.1.1')).toBe(true);
  expect(isPublicAddress('8.8.8.8')).toBe(true);
  expect(isPublicAddress('93.184.216.34')).toBe(true);
  expect(isPublicAddress('208.67.222.222')).toBe(true);
 });
 it('rejects all private IPv4 ranges (RFC 1918)',()=>{
  expect(isPublicAddress('10.0.0.1')).toBe(false);
  expect(isPublicAddress('10.255.255.255')).toBe(false);
  expect(isPublicAddress('172.16.0.1')).toBe(false);
  expect(isPublicAddress('172.31.255.255')).toBe(false);
  expect(isPublicAddress('192.168.0.1')).toBe(false);
  expect(isPublicAddress('192.168.255.255')).toBe(false);
 });
 it('rejects loopback addresses',()=>{
  expect(isPublicAddress('127.0.0.1')).toBe(false);
  expect(isPublicAddress('127.255.255.255')).toBe(false);
  expect(isPublicAddress('::1')).toBe(false);
 });
 it('rejects link-local addresses',()=>{
  expect(isPublicAddress('169.254.0.1')).toBe(false);
  expect(isPublicAddress('169.254.169.254')).toBe(false);
  expect(isPublicAddress('fe80::1')).toBe(false);
  expect(isPublicAddress('fe9a::1')).toBe(false);
 });
 it('rejects CGNAT shared address space (100.64.0.0/10)',()=>{
  expect(isPublicAddress('100.64.0.1')).toBe(false);
  expect(isPublicAddress('100.127.255.255')).toBe(false);
 });
 it('rejects documentation and benchmarking ranges',()=>{
  expect(isPublicAddress('192.0.2.1')).toBe(false);
  expect(isPublicAddress('198.51.100.1')).toBe(false);
  expect(isPublicAddress('203.0.113.1')).toBe(false);
  expect(isPublicAddress('198.18.0.1')).toBe(false);
 });
 it('rejects multicast and reserved IPv4',()=>{
  expect(isPublicAddress('224.0.0.1')).toBe(false);
  expect(isPublicAddress('240.0.0.1')).toBe(false);
  expect(isPublicAddress('255.255.255.255')).toBe(false);
 });
 it('rejects empty, non-string, and malformed inputs',()=>{
  expect(isPublicAddress('')).toBe(false);
  expect(isPublicAddress('not-an-ip')).toBe(false);
  expect(isPublicAddress('1.2.3')).toBe(false);
  expect(isPublicAddress('1.2.3.4.5')).toBe(false);
  expect(isPublicAddress(undefined as unknown as string)).toBe(false);
  expect(isPublicAddress(null as unknown as string)).toBe(false);
 });
 it('rejects IPv4-mapped IPv6 that maps to a private address',()=>{
  expect(isPublicAddress('::ffff:127.0.0.1')).toBe(false);
  expect(isPublicAddress('::ffff:10.0.0.1')).toBe(false);
  expect(isPublicAddress('::ffff:192.168.1.1')).toBe(false);
 });
 it('accepts IPv4-mapped IPv6 that maps to a public address',()=>{
  expect(isPublicAddress('::ffff:1.1.1.1')).toBe(true);
  expect(isPublicAddress('::ffff:8.8.8.8')).toBe(true);
 });
 it('accepts public IPv6 addresses',()=>{
  expect(isPublicAddress('2606:4700:4700::1111')).toBe(true);
  expect(isPublicAddress('2001:4860:4860::8888')).toBe(true);
 });
 it('rejects unique-local and multicast IPv6',()=>{
  expect(isPublicAddress('fc00::1')).toBe(false);
  expect(isPublicAddress('fd12:3456::1')).toBe(false);
  expect(isPublicAddress('ff02::1')).toBe(false);
 });
 it('rejects documentation IPv6 range (2001:db8::/32)',()=>{
  expect(isPublicAddress('2001:db8::1')).toBe(false);
 });
});
describe('normalizeAddress',()=>{
 it('strips ::ffff: prefix from valid IPv4-mapped IPv6 addresses',()=>{
  expect(normalizeAddress('::ffff:1.2.3.4')).toBe('1.2.3.4');
  expect(normalizeAddress('::ffff:8.8.8.8')).toBe('8.8.8.8');
  expect(normalizeAddress('::FFFF:1.2.3.4')).toBe('1.2.3.4');
 });
 it('returns plain IPv4 and IPv6 addresses unchanged',()=>{
  expect(normalizeAddress('1.2.3.4')).toBe('1.2.3.4');
  expect(normalizeAddress('2606:4700::1')).toBe('2606:4700::1');
  expect(normalizeAddress('::1')).toBe('::1');
 });
 it('returns the original when the suffix is not a valid dotted IPv4',()=>{
  expect(normalizeAddress('::ffff:not-valid')).toBe('::ffff:not-valid');
 });
});
describe('validateWebsiteUrl',()=>{
 it('accepts valid public HTTP and HTTPS URLs',()=>{
  expect(validateWebsiteUrl('https://example.com').hostname).toBe('example.com');
  expect(validateWebsiteUrl('http://example.com').hostname).toBe('example.com');
  expect(validateWebsiteUrl('https://example.com/path?q=1').pathname).toBe('/path');
  expect(validateWebsiteUrl('http://example.com:80').hostname).toBe('example.com');
  expect(validateWebsiteUrl('https://example.com:443').hostname).toBe('example.com');
 });
 it('rejects non-HTTP(S) protocols',()=>{
  expect(()=>validateWebsiteUrl('file:///etc/passwd')).toThrow(/HTTP or HTTPS/i);
  expect(()=>validateWebsiteUrl('ftp://example.com')).toThrow(/HTTP or HTTPS/i);
  expect(()=>validateWebsiteUrl('javascript:alert(1)')).toThrow();
 });
 it('rejects URLs with credentials',()=>{
  expect(()=>validateWebsiteUrl('http://user:pass@example.com')).toThrow(/public host/i);
  expect(()=>validateWebsiteUrl('http://user@example.com')).toThrow(/public host/i);
 });
 it('rejects non-standard ports',()=>{
  expect(()=>validateWebsiteUrl('http://example.com:8080')).toThrow(/standard web port/i);
  expect(()=>validateWebsiteUrl('https://example.com:8443')).toThrow(/standard web port/i);
 });
 it('rejects direct IP inputs that resolve to private addresses',()=>{
  expect(()=>validateWebsiteUrl('http://127.0.0.1')).toThrow(/public host/i);
  expect(()=>validateWebsiteUrl('http://10.0.0.1')).toThrow(/public host/i);
  expect(()=>validateWebsiteUrl('http://192.168.1.1')).toThrow(/public host/i);
  expect(()=>validateWebsiteUrl('http://169.254.169.254')).toThrow(/public host/i);
 });
 it('accepts direct IP inputs for public addresses',()=>{
  expect(validateWebsiteUrl('http://1.1.1.1').hostname).toBe('1.1.1.1');
  expect(validateWebsiteUrl('https://8.8.8.8').hostname).toBe('8.8.8.8');
 });
 it('rejects completely invalid URLs',()=>{
  expect(()=>validateWebsiteUrl('not a url')).toThrow(/valid/i);
  expect(()=>validateWebsiteUrl('')).toThrow();
 });
});